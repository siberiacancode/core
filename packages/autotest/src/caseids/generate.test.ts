it('Should use custom paths and symbol names', async () => {
  const project = await createProject();
  const casesFile = await writeProjectFile(
    project,
    'e2e/cases/profile/profile.ts',
    "export const cases = defineCases([{ name: 'Открытие профиля', steps: [] }]);\n"
  );

  const result = await generateCaseIds({
    cwd: project,
    constantName: 'TEST_CASE_IDS',
    functionName: 'defineCases',
    input: 'e2e/cases',
    lastIdName: 'LAST_TEST_CASE_ID',
    output: 'e2e/ids.ts',
    references: 'e2e'
  });

  expect(result.output).toBe(resolve(project, 'e2e/ids.ts'));
  expect(await readFile(casesFile, 'utf8')).toContain("id: '1'");
  expect(await readProjectFile(project, 'e2e/ids.ts')).toContain(
    'export const TEST_CASE_IDS = {'
  );
  expect(await readProjectFile(project, 'e2e/ids.ts')).toContain(
    'export const LAST_TEST_CASE_ID = 1;'
  );
});

it('Should reject duplicate case ID keys without changing files', async () => {
  const project = await createProject();
  const source = "export const cases = createTestCases([{ name: 'Один кейс', steps: [] }]);\n";
  const firstFile = await writeProjectFile(
    project,
    'tests/testcases/auth/first.ts',
    source
  );
  const secondFile = await writeProjectFile(
    project,
    'tests/testcases/auth/second.ts',
    source
  );
  const output = await writeProjectFile(project, 'tests/case-ids.ts', 'original output\n');

  await expect(generateCaseIds({ cwd: project })).rejects.toThrow(
    'duplicate case ID key AUTH_ODIN_KEYS'
  );
  expect(await readFile(firstFile, 'utf8')).toBe(source);
  expect(await readFile(secondFile, 'utf8')).toBe(source);
  expect(await readFile(output, 'utf8')).toBe('original output\n');
});

it('Should fail when the test case directory does not exist', async () => {
  const project = await createProject();

  await expect(generateCaseIds({ cwd: project })).rejects.toThrow(
    'test cases directory does not exist: tests/testcases'
  );
});
