import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';

import type { TestidNode } from '../../types';

interface Nested {
  [key: string]: string | Nested;
}

const nest = (nodes: TestidNode[]) => {
  const root: Nested = {};

  nodes.forEach((node) => {
    let cursor = root;

    node.path.slice(0, -1).forEach((segment) => {
      if (typeof cursor[segment] !== 'object') cursor[segment] = {};
      cursor = cursor[segment] as Nested;
    });

    cursor[node.path.at(-1)!] = node.id;
  });

  return root;
};

interface GenerateOptions {
  name: string;
}

export const generate = (nodes: TestidNode[], options: GenerateOptions) => {
  const name = options.name;

  return `/* eslint-disable */
/* prettier-ignore */
// generated by @siberiacancode/testids

export const ${name} = ${JSON.stringify(nest(nodes), null, 2)} as const;

type Leaves<T> = T extends string ? T : { [K in keyof T]: Leaves<T[K]> }[keyof T];

export type Testid = Leaves<typeof ${name}>;
`;
};

export const write = async (path: string, content: string) => {
  const current = await readFile(path, 'utf8').catch(() => null);
  if (current === content) return false;

  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content, 'utf8');

  return true;
};
